"""Replace raw-LaTeX "Code" paragraphs in the planning .docx with Word (OMML)
equations generated by pandoc, and turn V_P / V_S / 10^0.3 in body text into
real subscripts/superscripts. Everything else in the document is left as is.

usage: python -I fix_equations.py orig.docx eqs.docx out.docx
"""
import re
import sys
import zipfile

orig, eqs, out = sys.argv[1:4]
M_NS = 'xmlns:m="http://schemas.openxmlformats.org/officeDocument/2006/math"'

with zipfile.ZipFile(eqs) as z:
    ex = z.read('word/document.xml').decode('utf8')
omml = re.findall(r'<m:oMathPara>.*?</m:oMathPara>', ex, flags=re.S)
assert len(omml) == 5, len(omml)

with zipfile.ZipFile(orig) as z:
    doc = z.read('word/document.xml').decode('utf8')

# 1. Display equations: the five Code paragraphs, in document order.
code_para = re.compile(r'<w:p><w:pPr><w:pStyle w:val="Code"/></w:pPr>'
                       r'(?:(?!</w:p>).)*?bongo_lang_latex_\d+(?:(?!</w:p>).)*?</w:p>', re.S)
found = code_para.findall(doc)
assert len(found) == 5, f'expected 5 LaTeX code paragraphs, found {len(found)}'
it = iter(omml)
doc = code_para.sub(
    lambda m: ('<w:p><w:pPr><w:spacing w:before="120" w:after="120"/></w:pPr>'
               + next(it) + '</w:p>'), doc)
if 'xmlns:m=' not in doc[:2000]:
    doc = doc.replace('<w:document ', '<w:document ' + M_NS + ' ', 1)

# 2. Inline sub/superscripts inside ordinary runs.
TOKEN = re.compile(r'V_P|V_S|10\^0\.3')


def split_run(m):
    run = m.group(0)
    rpr_m = re.search(r'<w:rPr>(.*?)</w:rPr>', run, re.S)
    rpr = rpr_m.group(1) if rpr_m else ''
    t_m = re.search(r'<w:t(?: [^>]*)?>([^<]*)</w:t>', run)
    if not t_m or not TOKEN.search(t_m.group(1)) or '<w:t' not in run:
        return run

    def r(text, va=None):
        props = rpr + (f'<w:vertAlign w:val="{va}"/>' if va else '')
        props = f'<w:rPr>{props}</w:rPr>' if props else ''
        return f'<w:r>{props}<w:t xml:space="preserve">{text}</w:t></w:r>'

    parts, pos, text = [], 0, t_m.group(1)
    for tm in TOKEN.finditer(text):
        if tm.start() > pos:
            parts.append(r(text[pos:tm.start()]))
        tok = tm.group(0)
        if tok.startswith('V_'):
            parts += [r('V'), r(tok[2], 'subscript')]
        else:
            parts += [r('10'), r('0.3', 'superscript')]
        pos = tm.end()
    if pos < len(text):
        parts.append(r(text[pos:]))
    return ''.join(parts)


before = len(TOKEN.findall(doc))
doc = re.sub(r'<w:r>(?:(?!</w:r>).)*?</w:r>', split_run, doc, flags=re.S)
after = len(TOKEN.findall(doc))
print(f'equations replaced: 5; inline tokens fixed: {before - after} (left: {after})')

with zipfile.ZipFile(orig) as zin, zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zout:
    for item in zin.infolist():
        if item.is_dir():
            continue
        data = zin.read(item.filename)
        if item.filename == 'word/document.xml':
            data = doc.encode('utf8')
        zout.writestr(item, data)
print('wrote', out)
