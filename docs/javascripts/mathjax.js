// MathJax settings for pymdownx.arithmatex (generic mode), per the MkDocs
// Material docs: typeset only the math blocks, and again after instant loading.
window.MathJax = {
  tex: {
    inlineMath: [['\\(', '\\)']],
    displayMath: [['\\[', '\\]']],
    processEscapes: true,
    processEnvironments: true,
  },
  options: {
    ignoreHtmlClass: '.*|',
    processHtmlClass: 'arithmatex',
  },
};

if (typeof document$ !== 'undefined') {
  document$.subscribe(() => {
    if (!window.MathJax.typesetPromise) return;
    MathJax.startup.output.clearCache();
    MathJax.typesetClear();
    MathJax.texReset();
    MathJax.typesetPromise();
  });
}
